"use strict";

// Source modules share one private application scope. No game state is exposed
// on window; the browser receives a deterministic, dependency-free bundle.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const root = path.resolve(__dirname, "..");
const modules = JSON.parse(fs.readFileSync(path.join(root, "client/modules.json"), "utf8"));
const bundle = '"use strict";\n// Generated by npm run build. Edit client/ source modules.\n(() => {\n' +
  modules.map(name => `\n// Module: ${name}\n${fs.readFileSync(path.join(root, "client", name), "utf8")}`).join("\n") +
  "\n})();\n";
const cssNames = ["tokens.css", "base.css", "pages.css", "map.css", "battle.css", "motion.css", "training.css", "responsive.css", "combat-polish.css"];
const stylesheet = "/* Generated by npm run build. Edit client/styles/. */\n" +
  cssNames.map(name => `\n/* ${name} */\n${fs.readFileSync(path.join(root, "client/styles", name), "utf8")}`).join("\n");
function resourceFingerprint(dir) {
 const hash=crypto.createHash("sha256");
 for(const name of fs.readdirSync(dir).sort()){
  const file=path.join(dir,name);
  hash.update(name);hash.update(fs.statSync(file).isDirectory()?resourceFingerprint(file):fs.readFileSync(file));
 }
 return hash.digest("hex");
}
const revision = crypto.createHash("sha256").update(bundle).update(stylesheet).update(resourceFingerprint(path.join(root,"public/assets/images"))).update(resourceFingerprint(path.join(root,"public/assets/icons"))).update(fs.readFileSync(path.join(root,"public/js/theme-bootstrap.js"))).update(fs.readFileSync(path.join(root,"public/index.html"))).update(["game-data.js","ui-model.js","audio-system.js","tutorial-system.js","armory-lab.js"].map(file=>fs.readFileSync(path.join(root,"public/js",file),"utf8")).join("")).update(fs.existsSync(path.join(root,"public/assets/fonts"))?resourceFingerprint(path.join(root,"public/assets/fonts")):"no-fonts").digest("hex").slice(0, 10);
const assetVersion=JSON.parse(fs.readFileSync(path.join(root,"package.json"),"utf8")).version+"-ui2."+revision;
const versionedStylesheet=stylesheet.replace(/url\((["']?)(\/assets\/[^"')?]+)\1\)/g,(_all,quote,url)=>`url(${quote}${url}?v=${assetVersion}${quote})`);
for(const [file,content] of [["public/js/app.js",bundle],["public/css/ocean.css",versionedStylesheet]]){
 const dest=path.join(root,file);if(!fs.existsSync(dest)||fs.readFileSync(dest,"utf8")!==content)fs.writeFileSync(dest,content);
}
const motionSource=fs.readFileSync(path.join(root,"client/motion.js"),"utf8");
const motionObject=motionSource.slice(motionSource.indexOf("Object.freeze(")+14,motionSource.indexOf("  const motionRuntime")).trim().replace(/\);$/,"");
fs.writeFileSync(path.join(root,"public/js/armory-lab-config.js"),`"use strict";window.OCEAN_LAB_MOTION=Object.freeze(${motionObject});\n`);
const configPath = path.join(root, "public/js/release-config.js");
const releaseVersion = JSON.parse(fs.readFileSync(path.join(root,"package.json"),"utf8")).version;
const config = fs.readFileSync(configPath, "utf8").replace(/assetVersion: "[^"]+"/, `assetVersion: "${releaseVersion}-ui2.${revision}"`);
if (fs.readFileSync(configPath, "utf8") !== config) fs.writeFileSync(configPath, config);
console.log(`[Ocean UI] Built ${modules.length} private modules and ${cssNames.length} style layers.`);
