'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {once}=require('node:events');
const {createOceanServer}=require('../server/app');
const {InMemoryRoomService}=require('../server/game/room-service');
test('真实HTTP训练会话与正式房间隔离，凭证/版本/幂等/教官接口正确',async t=>{
 const formal=new InMemoryRoomService();
 const runtime=createOceanServer({roomService:formal,training:{debug:true}});
 runtime.httpServer.listen(0,'127.0.0.1');await once(runtime.httpServer,'listening');
 t.after(()=>new Promise(resolve=>runtime.io.close(resolve)));
 const base='http://127.0.0.1:'+runtime.httpServer.address().port;
 const request=async(path,method='GET',body,token)=>{
  const res=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(token?{'X-Training-Token':token}:{})},body:body?JSON.stringify(body):undefined});
  return {status:res.status,headers:res.headers,data:await res.json()};
 };
 const list=await request('/api/training/catalog');assert.equal(list.status,200);assert.equal(list.headers.get('cache-control'),'no-store');
 const created=await request('/api/training/sessions','POST',{scenarioId:'CAMP-W01'}),a=created.data.data;
 const b=(await request('/api/training/sessions','POST',{scenarioId:'CAMP-W01'})).data.data;
 assert.equal(formal.rooms.size,0);
 const match=formal.createRoom({nickname:'正式测试玩家'}),old=formal.rooms.get(match.roomCode).stateVersion;
 assert.equal((await request('/api/training/sessions/'+a.id,'GET',null,b.token)).status,401);
 assert.equal((await request('/api/training/sessions/'+a.id,'GET',null,match.reconnectToken)).status,401);
 assert.equal((await request('/api/training/sessions/'+a.id+'/reveal','GET',null,a.token)).status,400);
 const intent={actionId:'http-intent',actionType:a.task.action,sourceId:'destroyer-i',target:a.task.target};
 const payload={intent,expectedVersion:a.view.stateVersion,trainingGeneration:a.generation};
 const path='/api/training/sessions/'+a.id+'/commands',body={event:'action:submit',payload,operationId:'http-intent'};
 const acted=await request(path,'POST',body,a.token);assert.equal(acted.status,200);assert.equal(acted.data.data.task.completed,true);
 const duplicate=await request(path,'POST',body,a.token);assert.deepEqual(duplicate.data,acted.data);
 assert.equal(formal.rooms.get(match.roomCode).stateVersion,old);assert.equal(formal.rooms.size,1);
 const unsafe=await request(path,'POST',{event:'action:submit',payload:{...payload,intent:{...intent,target:{kind:'cell',coordinate:'L12'}}},operationId:'http-intent'},a.token);
 assert.equal(unsafe.status,400);assert.equal(unsafe.data.error.code,'ACTION_ID_REUSED');
 const stale=await request(path,'POST',{event:'training:control',payload:{control:'reveal',expectedVersion:1,trainingGeneration:a.generation},operationId:'stale'},a.token);
 assert.equal(stale.data.error.code,'STATE_VERSION_CONFLICT');
 const version=acted.data.data.view.stateVersion;
 const reveal=await request(path,'POST',{event:'training:control',payload:{control:'reveal',expectedVersion:version,trainingGeneration:a.generation},operationId:'reveal'},a.token);
 assert.equal(reveal.status,200);
 const coach=await request('/api/training/sessions/'+a.id+'/reveal','GET',null,a.token);
 assert.ok(coach.data.data.players['cadet-2']);assert.ok(coach.data.data.lessons.some(x=>x.includes('实际伤害')));
 assert.ok(!JSON.stringify(coach.data).includes(match.reconnectToken));
 await request('/api/training/sessions/'+a.id,'DELETE',null,a.token);
 assert.equal((await request('/api/training/sessions/'+a.id,'GET',null,a.token)).status,401);
 assert.equal((await request('/api/training/sessions','POST',{scenarioId:'free-practice',action:'invented_weapon',targetKind:'empty',sourceState:'normal'})).status,400);
});
